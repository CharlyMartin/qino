import { writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

import {
  AUTOGENERATED_FILE_NAME,
  CONFIG_FILE_NAME,
  ROOT_FOLDER_NAME,
} from "../../data";
import { type LockFile, LockFileSchema } from "../../schemas/lock-file";
import { assertDirectory, assertFile } from "../../utils";
import { assertNoOverlappingPaths } from "./assert-no-overlapping-paths";
import { buildCollectionsLock } from "./build-collections-lock";
import { buildSingletonsLock } from "./build-singletons-lock";
import { buildTreesLock } from "./build-trees-lock";
import { loadCollections } from "./load-collections";
import { loadConfig } from "./load-config";
import { loadSingletons } from "./load-singletons";
import { loadTrees } from "./load-trees";

declare const __QINO_VERSION__: string;

export async function runBuild() {
  const cwd = process.cwd();

  const qinoDir = join(cwd, ROOT_FOLDER_NAME);
  await assertDirectory(
    qinoDir,
    `"${ROOT_FOLDER_NAME}" folder not found at "${qinoDir}"`,
  );

  const configPath = join(qinoDir, CONFIG_FILE_NAME);
  await assertFile(
    configPath,
    `"${ROOT_FOLDER_NAME}/${CONFIG_FILE_NAME}" not found at "${configPath}"`,
  );

  const config = await loadConfig(configPath);

  const contentFolderAbs = resolve(cwd, config.contentFolder);
  await assertDirectory(
    contentFolderAbs,
    `contentFolder "${config.contentFolder}" is not a directory (resolved to ${contentFolderAbs})`,
  );

  const mediaFolderAbs = resolve(cwd, config.mediaFolder);
  await assertDirectory(
    mediaFolderAbs,
    `mediaFolder "${config.mediaFolder}" is not a directory (resolved to ${mediaFolderAbs})`,
  );

  const collections = await loadCollections(qinoDir);
  const singletons = await loadSingletons(qinoDir);
  const trees = await loadTrees(qinoDir);

  assertNoOverlappingPaths({
    collectionDirs: [...collections.keys()],
    singletonFiles: [...singletons.keys()],
    treeDirs: [...trees.keys()],
  });

  const collectionsLock = await buildCollectionsLock(
    contentFolderAbs,
    collections,
  );
  const singletonsLock = await buildSingletonsLock(
    contentFolderAbs,
    singletons,
  );
  const treesLock = await buildTreesLock(contentFolderAbs, trees);

  const lock: LockFile = LockFileSchema.parse({
    qinoVersion: __QINO_VERSION__,
    config: {
      contentFolder: config.contentFolder,
      mediaFolder: config.mediaFolder,
    },
    collections: collectionsLock,
    singletons: singletonsLock,
    trees: treesLock,
  });

  const lockPath = join(qinoDir, AUTOGENERATED_FILE_NAME);
  await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`, "utf8");
  console.log(`Wrote ${lockPath}`);
}
