import type { GenericPath } from "../../types/utils";

/**
 * Renders the `qino/_generated/types.d.ts` augmentation. Each entry becomes a named slug
 * alias plus a `QinoSlugRegistry` mapping keyed by the primitive's directory.
 * Slugs use the assistive form (`... | (string & {})`) so known slugs
 * autocomplete while any string is still accepted.
 */

export type GeneratedSlugEntry = {
  directory: GenericPath;
  typeName: string;
  slugs: Array<string>;
};

export const NEW_LINE = "\n";
export const EMPTY = "";
export const SPACE = " ";
export const TAB = "  ";
export const OPEN_BRACKET = "{";
export const CLOSING_BRACKET = "}";

export const BANNER =
  "// Generated by qino — do not edit. Run `qino build` to regenerate.";
export const EMPTY_EXPORT = "export {};";

export function renderGeneratedTypes(entries: Array<GeneratedSlugEntry>) {
  if (entries.length == 0) {
    return [BANNER, EMPTY_EXPORT].join(NEW_LINE);
  }

  const aliases = entries
    .map(
      (entry) =>
        `${TAB}export type${SPACE}${entry.typeName}${SPACE}=${SPACE}${renderUnion(entry.slugs)};`,
    )
    .join(NEW_LINE);

  const registry = entries
    .map(
      (entry) =>
        `${TAB}${TAB}${JSON.stringify(entry.directory)}:${SPACE}${entry.typeName};`,
    )
    .join(NEW_LINE);

  return [
    BANNER,
    EMPTY,
    EMPTY_EXPORT,
    EMPTY,
    `declare${SPACE}module${SPACE}"@qino/cms"${SPACE}${OPEN_BRACKET}`,
    aliases,
    EMPTY,
    `${TAB}interface${SPACE}QinoSlugRegistry${SPACE}${OPEN_BRACKET}`,
    registry,
    `${TAB}${CLOSING_BRACKET}`,
    CLOSING_BRACKET,
    EMPTY,
  ].join(NEW_LINE);
}

function renderUnion(slugs: Array<string>) {
  return [
    ...slugs.map((slug) => JSON.stringify(slug)),
    `(string${SPACE}&${SPACE}${OPEN_BRACKET}${CLOSING_BRACKET})`,
  ].join(`${SPACE}|${SPACE}`);
}
